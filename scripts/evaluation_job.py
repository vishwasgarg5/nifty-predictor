def print_ledger_result(
    title: str,
    result: dict[str, Any],
) -> None:
    """Print one ledger evaluation summary."""

    print()

    print(title)

    print("-" * 70)

    print(
        "Status: "
        f"{result.get('status')}"
    )

    print(
        "Path: "
        f"{result.get('path')}"
    )

    print(
        "Total records: "
        f"{result.get('total_records', 0)}"
    )

    print(
        "Pending before: "
        f"{result.get('pending_before', 0)}"
    )

    print(
        "Evaluated: "
        f"{result.get('evaluated', 0)}"
    )

    print(
        "Waiting: "
        f"{result.get('waiting', 0)}"
    )

    print(
        "Invalid: "
        f"{result.get('invalid', 0)}"
    )

    print(
        "Already evaluated: "
        f"{result.get('already_evaluated', 0)}"
    )

    print(
        "Ledger updated: "
        f"{result.get('updated', False)}"
    )

    if result.get("error"):

        print(
            "Error: "
            f"{result.get('error')}"
        )


def main() -> int:
    """
    CLI entry point.
    """

    result = (
        run_evaluation_job()
    )

    print()

    print("=" * 70)

    print("PREDICTION EVALUATION JOB RESULT")

    print("=" * 70)

    print_ledger_result(
        "PRODUCTION LEDGER",
        result.get(
            "production",
            {},
        ),
    )

    print_ledger_result(
        "SHADOW LEDGER",
        result.get(
            "shadow",
            {},
        ),
    )

    print()

    print("=" * 70)

    print(
        "FINAL STATUS: "
        f"{result.get('status')}"
    )

    print("=" * 70)

    if result.get("error"):

        print()

        print(
            "Error: "
            f"{result.get('error')}"
        )

    return (
        0
        if result.get("status")
        in {
            "SUCCESS",
            "PARTIAL_SUCCESS",
        }
        else 1
    )


if __name__ == "__main__":

    raise SystemExit(
        main()
    )
