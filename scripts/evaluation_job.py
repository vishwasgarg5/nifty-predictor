# ============================================================

def utc_now() -> datetime:
    """Return the current UTC datetime."""

    return datetime.now(
        timezone.utc
    )


def utc_now_iso() -> str:
    """Return the current UTC datetime as ISO text."""

    return utc_now().isoformat()


# ============================================================
# CONFIG HELPERS
# ============================================================

def object_to_dict(
    value: Any,
) -> dict[str, Any]:
    """
    Convert a configuration object into a dictionary.
    """

    if value is None:
        return {}

    if isinstance(value, dict):
        return dict(value)

    if hasattr(value, "items"):
        try:
            return dict(value.items())
        except Exception:
            pass

    if hasattr(value, "__dict__"):
        return {
            key: item
            for key, item in vars(value).items()
            if not key.startswith("_")
        }

    return {}


def load_config() -> Any:
    """
    Load project configuration.
    """

    try:

        from src.config import cfg

        return cfg

    except Exception as error:

        logger.warning(
            "Could not import src.config.cfg: %s",
            error,
        )

        return None


# ============================================================
# LEDGER PATHS
# ============================================================

def resolve_project_path(
    value: str | Path,
) -> Path:
    """
    Convert a relative project path into an absolute path.
    """

    path = Path(
        str(value)
    )

    if not path.is_absolute():

        path = (
            PROJECT_ROOT
            / path
        )

    return path


def get_production_ledger_path() -> Path:
    """
    Get the production prediction ledger path.

    Supported configuration:

        data:
            prediction_ledger: ...

        paths:
            prediction_ledger: ...

    Default:

        data/ledger/predictions.csv
    """

    cfg = load_config()

    candidates: list[Any] = []

    if cfg is not None:

        data_section = getattr(
            cfg,
            "data",
            None,
        )

        data_values = object_to_dict(
            data_section
        )

        for key in [
            "prediction_ledger",
            "ledger",
        ]:

            value = data_values.get(
                key
            )

            if value:
                candidates.append(
                    value
                )

        paths_section = getattr(
            cfg,
            "paths",
            None,
        )

        paths_values = object_to_dict(
            paths_section
        )

        for key in [
            "prediction_ledger",
            "ledger",
        ]:

            value = paths_values.get(
                key
            )

            if value:
                candidates.append(
                    value
                )

    for candidate in candidates:

        if candidate:

            return resolve_project_path(
                candidate
            )

    return (
        PROJECT_ROOT
        / "data"
        / "ledger"
        / "predictions.csv"
    )


def get_shadow_ledger_path() -> Path:
    """
    Get the Champion / Challenger shadow ledger path.

    Supported configuration:

        shadow_predictions:
            ledger_file: ...

    Default:

        data/ledger/shadow_predictions.csv
    """

    cfg = load_config()

    if cfg is not None:

        shadow_section = getattr(
            cfg,
            "shadow_predictions",
            None,
        )

        values = object_to_dict(
            shadow_section
        )

        value = values.get(
            "ledger_file"
        )

        if value:

            return resolve_project_path(
                value
            )

    return (
        PROJECT_ROOT
        / "data"
        / "ledger"
        / "shadow_predictions.csv"
    )


# ============================================================
# DATAFRAME HELPERS
# ============================================================

def ensure_dataframe(
    value: Any,
) -> pd.DataFrame:
    """
    Convert supported data structures into a DataFrame.
    """

    if value is None:
        return pd.DataFrame()

    if isinstance(value, pd.DataFrame):
        return value.copy()

    if isinstance(value, pd.Series):
        return value.to_frame().T

    if isinstance(value, list):

        try:
            return pd.DataFrame(
                value
            )

        except Exception:
            return pd.DataFrame()

    if isinstance(value, dict):

        try:
            return pd.DataFrame(
                [value]
            )

        except Exception:
            return pd.DataFrame()

    return pd.DataFrame()


def normalize_status(
    value: Any,
) -> str:
    """
    Normalize evaluation status.
    """

    if value is None:
        return "PENDING"

    if pd.isna(value):
        return "PENDING"

    text = str(value).strip().upper()

    if not text:
        return "PENDING"

    return text


# ============================================================
# LEDGER READING
# ============================================================

def load_ledger(
    path: Path,
) -> pd.DataFrame:
    """
    Load a prediction ledger safely.
    """

    if not path.exists():

        logger.warning(
            "Ledger does not exist: %s",
            path,
        )

        return pd.DataFrame()

    try:

        frame = pd.read_csv(
            path
        )

    except pd.errors.EmptyDataError:

        logger.warning(
            "Ledger is empty: %s",
            path,
        )

        return pd.DataFrame()

    except Exception as error:

        raise RuntimeError(
            f"Could not read ledger {path}: {error}"
        ) from error

    return frame


# ============================================================
# PENDING PREDICTIONS
# ============================================================

def get_pending_predictions(
    ledger: pd.DataFrame,
) -> pd.DataFrame:
    """
    Return predictions requiring evaluation.

    EVALUATED rows are skipped.

    WAITING and PENDING rows are rechecked because the
    evaluation horizon may now have been reached.

    INVALID rows are skipped.
    """

    if ledger.empty:
        return ledger.copy()

    frame = ledger.copy()

    if "evaluation_status" not in frame.columns:

        frame["evaluation_status"] = (
            "PENDING"
        )

        return frame

    normalized_status = (
        frame["evaluation_status"]
        .apply(normalize_status)
    )

    pending_mask = ~normalized_status.isin(
        {
            "EVALUATED",
            "INVALID",
        }
    )

    return (
        frame.loc[
            pending_mask
        ]
        .copy()
    )


# ============================================================
# LEDGER UPDATE
# ============================================================

def merge_evaluation_results(
    original: pd.DataFrame,
    evaluated: pd.DataFrame,
) -> pd.DataFrame:
    """
    Merge evaluated rows back into the original ledger.

    Index positions are preserved because the evaluation job
    passes pending rows with their original DataFrame index.
    """

    if original.empty:
        return evaluated.copy()

    if evaluated.empty:
        return original.copy()

    result = original.copy()

    for index, row in evaluated.iterrows():

        if index not in result.index:
            continue

        for column, value in row.items():

            if column not in result.columns:

                result[column] = pd.NA

            result.at[
                index,
                column,
            ] = value

    return result


def save_ledger(
    ledger: pd.DataFrame,
    path: Path,
) -> None:
    """
    Save the updated ledger atomically.
    """

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    temporary_path = (
        path.with_suffix(
            path.suffix + ".tmp"
        )
    )

    try:

        ledger.to_csv(
            temporary_path,
            index=False,
        )

        temporary_path.replace(
            path
        )

    except Exception as error:

        if temporary_path.exists():

            try:
                temporary_path.unlink()
            except Exception:
                pass

        raise RuntimeError(
            f"Could not save ledger {path}: {error}"
        ) from error

    logger.info(
        "Saved %s record(s) to %s",
        len(ledger),
        path,
    )


# ============================================================
# OUTCOME RESOLUTION
# ============================================================

def resolve_actual_outcomes(
    predictions: pd.DataFrame,
) -> pd.DataFrame:
    """
    Call the project's actual outcome resolver.
    """

    try:

        from src.actuals import (
            resolve_actual_outcomes
            as resolver,
        )

        logger.info(
            "Using src.actuals.resolve_actual_outcomes()."
        )

        result = resolver(
            predictions
        )

        return ensure_dataframe(
            result
        )

    except ImportError:

        pass

    except Exception as error:

        logger.warning(
            "src.actuals resolver failed: %s",
            error,
        )

    try:

        from src.actual_outcomes import (
            resolve_actual_outcomes
            as resolver,
        )

        logger.info(
            "Using "
            "src.actual_outcomes."
            "resolve_actual_outcomes()."
        )

        result = resolver(
            predictions
        )

        return ensure_dataframe(
            result
        )

    except ImportError:

        pass

    except Exception as error:

        logger.warning(
            "src.actual_outcomes resolver failed: %s",
            error,
        )

    try:

        from src.actuals import (
            fetch_actuals,
        )

        logger.info(
            "Using src.actuals.fetch_actuals()."
        )

        result = fetch_actuals(
            predictions
        )

        return ensure_dataframe(
            result
        )

    except Exception as error:

        raise RuntimeError(
            "Could not find a working actual outcome "
            f"resolver: {error}"
        ) from error


# ============================================================
# SINGLE LEDGER EVALUATION
# ============================================================

def evaluate_ledger(
    name: str,
    path: Path,
) -> dict[str, Any]:
    """
    Evaluate all pending predictions in one ledger.
    """

    result: dict[str, Any] = {
        "name": name,
        "path": str(path),
        "status": "STARTED",
        "total_records": 0,
        "pending_before": 0,
        "evaluated": 0,
        "waiting": 0,
        "invalid": 0,
        "already_evaluated": 0,
        "updated": False,
        "error": None,
    }

    logger.info(
        "-" * 70
    )

    logger.info(
        "Evaluating %s ledger: %s",
        name,
        path,
    )

    logger.info(
        "-" * 70
    )

    # --------------------------------------------------------
    # LOAD
    # --------------------------------------------------------

    ledger = load_ledger(
        path
    )

    result[
        "total_records"
    ] = len(
        ledger
    )

    if ledger.empty:

        result["status"] = "EMPTY"

        return result

    # --------------------------------------------------------
    # STATUS COUNTS
    # --------------------------------------------------------

    if "evaluation_status" in ledger.columns:

        statuses = (
            ledger[
                "evaluation_status"
            ]
            .apply(
                normalize_status
            )
        )

        result[
            "already_evaluated"
        ] = int(
            (
                statuses == "EVALUATED"
            ).sum()
        )

    # --------------------------------------------------------
    # PENDING
    # --------------------------------------------------------

    pending = (
        get_pending_predictions(
            ledger
        )
    )

    result[
        "pending_before"
    ] = len(
        pending
    )

    if pending.empty:

        result["status"] = (
            "NOTHING_TO_EVALUATE"
        )

        return result

    logger.info(
        "%s pending prediction(s) found.",
        len(pending),
    )

    # --------------------------------------------------------
    # ACTUAL OUTCOMES
    # --------------------------------------------------------

    evaluated = (
        resolve_actual_outcomes(
            pending
        )
    )

    if evaluated.empty:

        result["status"] = (
            "NO_RESULTS"
        )

        return result

    # --------------------------------------------------------
    # MERGE
    # --------------------------------------------------------

    updated_ledger = (
        merge_evaluation_results(
            original=ledger,
            evaluated=evaluated,
        )
    )

    # --------------------------------------------------------
    # STATUS COUNTS AFTER EVALUATION
    # --------------------------------------------------------

    if "evaluation_status" in evaluated.columns:

        statuses = (
            evaluated[
                "evaluation_status"
            ]
            .apply(
                normalize_status
            )
        )

        result["evaluated"] = int(
            (
                statuses == "EVALUATED"
            ).sum()
        )

        result["waiting"] = int(
            (
                statuses == "WAITING"
            ).sum()
        )

        result["invalid"] = int(
            (
                statuses == "INVALID"
            ).sum()
        )

    # --------------------------------------------------------
    # SAVE
    # --------------------------------------------------------

    save_ledger(
        updated_ledger,
        path,
    )

    result["updated"] = True

    if result["evaluated"] > 0:

        result["status"] = (
            "EVALUATED"
        )

    elif result["waiting"] > 0:

        result["status"] = (
            "WAITING"
        )

    else:

        result["status"] = (
            "COMPLETED"
        )

    return result


# ============================================================
# MAIN JOB
# ============================================================

def run_evaluation_job() -> dict[str, Any]:
    """
    Run evaluation for both production and shadow ledgers.
    """

    result: dict[str, Any] = {
        "started_at": utc_now_iso(),
        "status": "STARTED",
        "production": {},
        "shadow": {},
        "error": None,
    }

    logger.info(
        "=" * 70
    )

    logger.info(
        "STARTING PREDICTION EVALUATION JOB"
    )

    logger.info(
        "=" * 70
    )

    try:

        # ----------------------------------------------------
        # PRODUCTION LEDGER
        # ----------------------------------------------------

        production_path = (
            get_production_ledger_path()
        )

        try:

            production_result = (
                evaluate_ledger(
                    name="PRODUCTION",
                    path=production_path,
                )
            )

            result[
                "production"
            ] = production_result

        except Exception as error:

            logger.exception(
                "Production ledger evaluation failed."
            )

            result[
                "production"
            ] = {
                "name": "PRODUCTION",
                "path": str(
                    production_path
                ),
                "status": "FAILED",
                "error": str(error),
            }

        # ----------------------------------------------------
        # SHADOW LEDGER
        # ----------------------------------------------------

        shadow_path = (
            get_shadow_ledger_path()
        )

        try:

            shadow_result = (
                evaluate_ledger(
                    name="SHADOW",
                    path=shadow_path,
                )
            )

            result[
                "shadow"
            ] = shadow_result

        except Exception as error:

            logger.exception(
                "Shadow ledger evaluation failed."
            )

            result[
                "shadow"
            ] = {
                "name": "SHADOW",
                "path": str(
                    shadow_path
                ),
                "status": "FAILED",
                "error": str(error),
            }

        # ----------------------------------------------------
        # FINAL STATUS
        # ----------------------------------------------------

        production_status = str(
            result[
                "production"
            ].get(
                "status",
                "UNKNOWN",
            )
        ).upper()

        shadow_status = str(
            result[
                "shadow"
            ].get(
                "status",
                "UNKNOWN",
            )
        ).upper()

        failures = {
            "FAILED",
        }

        if (
            production_status in failures
            and shadow_status in failures
        ):

            result["status"] = "FAILED"

        elif (
            production_status in failures
            or shadow_status in failures
        ):

            result["status"] = (
                "PARTIAL_SUCCESS"
            )

        else:

            result["status"] = "SUCCESS"

        return result

    except Exception as error:

        logger.exception(
            "Evaluation job failed."
        )

        result["status"] = "FAILED"

        result["error"] = str(
            error
        )

        result["traceback"] = (
            traceback.format_exc()
        )

        return result

    finally:

        result["finished_at"] = (
            utc_now_iso()
        )

        logger.info(
            "=" * 70
        )

        logger.info(
            "EVALUATION JOB FINISHED | "
            "STATUS=%s",
            result.get(
                "status"
            ),
        )

        logger.info(
            "=" * 70
        )


