#!/usr/bin/env python3

"""
Prediction Evaluation Job.

This job evaluates pending market predictions against actual
market outcomes.

It evaluates two ledgers:

1. Production Prediction Ledger
   data/ledger/predictions.csv

2. Shadow Prediction Ledger
   data/ledger/shadow_predictions.csv

The shadow ledger contains predictions generated by both the
Champion and Challenger models using the same market data.

Pipeline
--------
Prediction Ledger
        │
        ▼
Find Pending Predictions
        │
        ▼
Actual Outcome Resolver
        │
        ├── actual_return
        ├── actual_direction
        ├── actual_risk
        └── evaluation_status
        │
        ▼
Update Ledger
        │
        ├── predictions.csv
        └── shadow_predictions.csv
        │
        ▼
Model Evaluation / Champion Challenger Comparison

Important
---------
This job only evaluates predictions whose evaluation_status is
not already EVALUATED.

WAITING predictions remain in the ledger until their configured
evaluation horizon has been reached.

INVALID predictions are preserved and are not automatically
re-evaluated unless their status is changed manually.

The job is safe to run repeatedly.
"""

