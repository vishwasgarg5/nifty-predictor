def object_to_dict(
    value: Any,
) -> dict[str, Any]:
    """Convert a configuration object into a dictionary."""

    if value is None:
        return {}

    if isinstance(value, dict):
        return dict(value)

    if hasattr(value, "items"):

        try:
            return dict(value.items())
        except Exception:
            pass

    if hasattr(value, "__dict__"):

        return {
            key: item
            for key, item in vars(value).items()
            if not key.startswith("_")
        }

    return {}


def load_config() -> Any:
    """Load project configuration."""

    try:

        from src.config import cfg

        return cfg

    except Exception as error:

        logger.warning(
            "Could not load config: %s",
            error,
        )

        return None


def get_champion_challenger_config() -> dict[str, Any]:
    """
    Load Champion / Challenger evaluation settings.

    Expected config section:

        champion_challenger:
            min_samples: 30
            min_direction_accuracy: 0.50
            min_performance_improvement: 0.05
            max_return_mae: 10.0
            max_risk_mae: 10.0
    """

    defaults = {
        "min_samples": 30,
        "min_direction_accuracy": 0.50,
        "min_performance_improvement": 0.05,
        "max_return_mae": 10.0,
        "max_risk_mae": 10.0,
    }

    cfg = load_config()

    if cfg is None:
        return defaults

    section = getattr(
        cfg,
        "champion_challenger",
        None,
    )

    values = object_to_dict(
        section
    )

    result = defaults.copy()

    for key in defaults:

        if key in values:
            result[key] = values[key]

    try:
        result["min_samples"] = max(
            1,
            int(result["min_samples"]),
        )
    except Exception:
        result["min_samples"] = defaults[
            "min_samples"
        ]

    for key in [
        "min_direction_accuracy",
        "min_performance_improvement",
        "max_return_mae",
        "max_risk_mae",
    ]:

        try:
            result[key] = float(
                result[key]
            )
        except Exception:
            result[key] = float(
                defaults[key]
            )

    return result


# ============================================================
# DATA HELPERS
# ============================================================

def find_column(
    frame: pd.DataFrame,
    candidates: list[str],
) -> str | None:
    """Find the first matching column."""

    for column in candidates:

        if column in frame.columns:
            return column

    return None


def safe_numeric_series(
    frame: pd.DataFrame,
    column: str | None,
) -> pd.Series:
    """Return a numeric series or empty series."""

    if column is None:
        return pd.Series(
            dtype=float
        )

    if column not in frame.columns:
        return pd.Series(
            dtype=float
        )

    return pd.to_numeric(
        frame[column],
        errors="coerce",
    )


def normalize_direction(
    value: Any,
) -> str | None:
    """Normalize direction labels."""

    if value is None:
        return None

    if pd.isna(value):
        return None

    text = str(value).strip().upper()

    mapping = {
        "BUY": "UP",
        "BULLISH": "UP",
        "LONG": "UP",
        "UP": "UP",

        "SELL": "DOWN",
        "BEARISH": "DOWN",
        "SHORT": "DOWN",
        "DOWN": "DOWN",

        "FLAT": "FLAT",
        "NEUTRAL": "FLAT",
        "SIDEWAYS": "FLAT",
    }

    return mapping.get(
        text,
        text,
    )


# ============================================================
# FILTER EVALUATED PREDICTIONS
# ============================================================

def get_evaluated_predictions(
    predictions: pd.DataFrame,
) -> pd.DataFrame:
    """
    Keep only successfully evaluated predictions.
    """

    if predictions is None:
        return pd.DataFrame()

    if predictions.empty:
        return predictions.copy()

    frame = predictions.copy()

    if "evaluation_status" not in frame.columns:

        logger.warning(
            "evaluation_status column missing."
        )

        return pd.DataFrame()

    statuses = (
        frame["evaluation_status"]
        .astype(str)
        .str.strip()
        .str.upper()
    )

    return (
        frame.loc[
            statuses == "EVALUATED"
        ]
        .copy()
    )


# ============================================================
# MODEL IDENTIFICATION
# ============================================================

def get_model_column(
    predictions: pd.DataFrame,
) -> str | None:
    """
    Find the model identifier column.
    """

    return find_column(
        predictions,
        [
            "model",
            "model_name",
            "model_type",
            "model_version",
            "prediction_model",
        ],
    )


def split_models(
    predictions: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Split predictions into Champion and Challenger groups.
    """

    model_column = get_model_column(
        predictions
    )

    if model_column is None:

        logger.warning(
            "No model column found."
        )

        return (
            pd.DataFrame(),
            pd.DataFrame(),
        )

    normalized = (
        predictions[model_column]
        .astype(str)
        .str.strip()
        .str.upper()
    )

    champion = (
        predictions.loc[
            normalized == "CHAMPION"
        ]
        .copy()
    )

    challenger = (
        predictions.loc[
            normalized == "CHALLENGER"
        ]
        .copy()
    )

    return (
        champion,
        challenger,
    )


# ============================================================
# DIRECTION ACCURACY
# ============================================================

def calculate_direction_accuracy(
    frame: pd.DataFrame,
) -> float | None:
    """
    Calculate prediction direction accuracy.

    Returns a value between 0 and 1.
    """

    predicted_column = find_column(
        frame,
        [
            "predicted_direction",
            "direction",
            "direction_prediction",
        ],
    )

    actual_column = find_column(
        frame,
        [
            "actual_direction",
        ],
    )

    if (
        predicted_column is None
        or actual_column is None
    ):
        return None

    correct = 0
    total = 0

    for _, row in frame.iterrows():

        predicted = normalize_direction(
            row.get(
                predicted_column
            )
        )

        actual = normalize_direction(
            row.get(
                actual_column
            )
        )

        if (
            predicted is None
            or actual is None
        ):
            continue

        total += 1

        if predicted == actual:
            correct += 1

    if total == 0:
        return None

    return correct / total


# ============================================================
# RETURN METRICS
# ============================================================

def calculate_return_metrics(
    frame: pd.DataFrame,
) -> dict[str, float | None]:
    """
    Calculate actual return and prediction error metrics.
    """

    actual_column = find_column(
        frame,
        [
            "actual_return",
        ],
    )

    predicted_column = find_column(
        frame,
        [
            "predicted_return",
            "expected_return",
            "return_prediction",
        ],
    )

    result: dict[str, float | None] = {
        "average_actual_return": None,
        "median_actual_return": None,
        "return_mae": None,
        "return_rmse": None,
    }

    actual = safe_numeric_series(
        frame,
        actual_column,
    )

    if not actual.empty:

        actual = actual.dropna()

        if not actual.empty:

            result[
                "average_actual_return"
            ] = float(
                actual.mean()
            )

            result[
                "median_actual_return"
            ] = float(
                actual.median()
            )

    if (
        actual_column is None
        or predicted_column is None
    ):
        return result

    paired = frame[
        [
            actual_column,
            predicted_column,
        ]
    ].copy()

    paired[actual_column] = (
        pd.to_numeric(
            paired[actual_column],
            errors="coerce",
        )
    )

    paired[predicted_column] = (
        pd.to_numeric(
            paired[predicted_column],
            errors="coerce",
        )
    )

    paired = paired.dropna()

    if paired.empty:
        return result

    errors = (
        paired[predicted_column]
        - paired[actual_column]
    )

    result["return_mae"] = float(
        errors.abs().mean()
    )

    result["return_rmse"] = float(
        math.sqrt(
            (errors ** 2).mean()
        )
    )

    return result


# ============================================================
# RISK METRICS
# ============================================================

def calculate_risk_metrics(
    frame: pd.DataFrame,
) -> dict[str, float | None]:
    """
    Calculate actual risk and risk prediction error.
    """

    actual_column = find_column(
        frame,
        [
            "actual_risk",
        ],
    )

    predicted_column = find_column(
        frame,
        [
            "predicted_risk",
            "risk_score",
            "risk",
        ],
    )

    result: dict[str, float | None] = {
        "average_actual_risk": None,
        "risk_mae": None,
    }

    actual = safe_numeric_series(
        frame,
        actual_column,
    )

    if not actual.empty:

        actual = actual.dropna()

        if not actual.empty:

            result[
                "average_actual_risk"
            ] = float(
                actual.mean()
            )

    if (
        actual_column is None
        or predicted_column is None
    ):
        return result

    paired = frame[
        [
            actual_column,
            predicted_column,
        ]
    ].copy()

    paired[actual_column] = (
        pd.to_numeric(
            paired[actual_column],
            errors="coerce",
        )
    )

    paired[predicted_column] = (
        pd.to_numeric(
            paired[predicted_column],
            errors="coerce",
        )
    )

    paired = paired.dropna()

    if paired.empty:
        return result

    errors = (
        paired[predicted_column]
        - paired[actual_column]
    )

    result["risk_mae"] = float(
        errors.abs().mean()
    )

    return result


# ============================================================
# COMPOSITE PERFORMANCE SCORE
# ============================================================

def calculate_performance_score(
    metrics: dict[str, Any],
) -> float | None:
    """
    Calculate a composite performance score.

    Higher is better.

    Formula:

        score =
            average_actual_return
            + direction_accuracy * 100
            - return_mae
            - risk_mae

    Missing metrics are treated conservatively as zero
    contribution.
    """

    actual_return = (
        metrics.get(
            "average_actual_return"
        )
        or 0.0
    )

    direction_accuracy = (
        metrics.get(
            "direction_accuracy"
        )
        or 0.0
    )

    return_mae = (
        metrics.get(
            "return_mae"
        )
        or 0.0
    )

    risk_mae = (
        metrics.get(
            "risk_mae"
        )
        or 0.0
    )

    score = (
        float(actual_return)
        + (
            float(direction_accuracy)
            * 100.0
        )
        - float(return_mae)
        - float(risk_mae)
    )

    return float(score)


# ============================================================
# MODEL METRICS
# ============================================================

def calculate_model_metrics(
    predictions: pd.DataFrame,
    model_name: str,
) -> dict[str, Any]:
    """
    Calculate all performance metrics for one model.
    """

    result: dict[str, Any] = {
        "model": model_name,
        "sample_size": int(
            len(predictions)
        ),
        "direction_accuracy": None,
        "average_actual_return": None,
        "median_actual_return": None,
        "return_mae": None,
        "return_rmse": None,
        "average_actual_risk": None,
        "risk_mae": None,
        "performance_score": None,
    }

    if predictions.empty:
        return result

    direction_accuracy = (
        calculate_direction_accuracy(
            predictions
        )
    )

    return_metrics = (
        calculate_return_metrics(
            predictions
        )
    )

    risk_metrics = (
        calculate_risk_metrics(
            predictions
        )
    )

    result[
        "direction_accuracy"
    ] = direction_accuracy

    result.update(
        return_metrics
    )

    result.update(
        risk_metrics
    )

    result[
        "performance_score"
    ] = (
        calculate_performance_score(
            result
        )
    )

    return result


# ============================================================
# PERFORMANCE IMPROVEMENT
# ============================================================

def calculate_improvement(
    champion_score: float | None,
    challenger_score: float | None,
) -> float | None:
    """
    Calculate Challenger improvement over Champion.

    Returns a decimal ratio.

    Example:

        Champion = 50
        Challenger = 55

        Improvement = 0.10
    """

    if champion_score is None:
        return None

    if challenger_score is None:
        return None

    champion = float(
        champion_score
    )

    challenger = float(
        challenger_score
    )

    if champion == 0:

        return (
            challenger
            - champion
        )

    return (
        challenger
        - champion
    ) / abs(
        champion
    )


# ============================================================
# PROMOTION ELIGIBILITY
# ============================================================

def evaluate_promotion_eligibility(
    champion_metrics: dict[str, Any],
    challenger_metrics: dict[str, Any],
    config: dict[str, Any],
) -> dict[str, Any]:
    """
    Determine whether the Challenger is eligible
    for promotion.

    This function does NOT promote the model.
    """

    reasons: list[str] = []

    min_samples = int(
        config[
            "min_samples"
        ]
    )

    min_direction_accuracy = float(
        config[
            "min_direction_accuracy"
        ]
    )

    min_improvement = float(
        config[
            "min_performance_improvement"
        ]
    )

    max_return_mae = float(
        config[
            "max_return_mae"
        ]
    )

    max_risk_mae = float(
        config[
            "max_risk_mae"
        ]
    )

    sample_size = int(
        challenger_metrics.get(
            "sample_size",
            0,
        )
    )

    if sample_size < min_samples:

        reasons.append(
            "Insufficient Challenger sample size "
            f"({sample_size}/{min_samples})."
        )

    direction_accuracy = (
        challenger_metrics.get(
            "direction_accuracy"
        )
    )

    if direction_accuracy is None:

        reasons.append(
            "Challenger direction accuracy "
            "is unavailable."
        )

    elif float(
        direction_accuracy
    ) < min_direction_accuracy:

        reasons.append(
            "Challenger direction accuracy below "
            f"threshold ({direction_accuracy:.4f} "
            f"< {min_direction_accuracy:.4f})."
        )

    return_mae = (
        challenger_metrics.get(
            "return_mae"
        )
    )

    if return_mae is None:

        reasons.append(
            "Challenger return MAE "
            "is unavailable."
        )

    elif float(
        return_mae
    ) > max_return_mae:

        reasons.append(
            "Challenger return MAE exceeds limit "
            f"({return_mae:.4f} "
            f"> {max_return_mae:.4f})."
        )

    risk_mae = (
        challenger_metrics.get(
            "risk_mae"
        )
    )

    if risk_mae is None:

        reasons.append(
            "Challenger risk MAE "
            "is unavailable."
        )

    elif float(
        risk_mae
    ) > max_risk_mae:

        reasons.append(
            "Challenger risk MAE exceeds limit "
            f"({risk_mae:.4f} "
            f"> {max_risk_mae:.4f})."
        )

    improvement = (
        calculate_improvement(
            champion_metrics.get(
                "performance_score"
            ),
            challenger_metrics.get(
                "performance_score"
            ),
        )
    )

    if improvement is None:

        reasons.append(
            "Performance improvement "
            "cannot be calculated."
        )

    elif improvement < min_improvement:

        reasons.append(
            "Challenger performance improvement "
            f"below threshold ({improvement:.4f} "
            f"< {min_improvement:.4f})."
        )

    eligible = (
        len(reasons) == 0
    )

    return {
        "eligible": eligible,
        "promotion_recommended": eligible,
        "performance_improvement": improvement,
        "reasons": reasons,
        "requirements": {
            "min_samples": min_samples,
            "min_direction_accuracy": (
                min_direction_accuracy
            ),
            "min_performance_improvement": (
                min_improvement
            ),
            "max_return_mae": (
                max_return_mae
            ),
            "max_risk_mae": (
                max_risk_mae
            ),
        },
    }


# ============================================================
# MAIN COMPARISON
# ============================================================

def compare_models(
    shadow_predictions: pd.DataFrame,
) -> dict[str, Any]:
    """
    Compare Champion and Challenger models.
    """

    config = (
        get_champion_challenger_config()
    )

    evaluated = (
        get_evaluated_predictions(
            shadow_predictions
        )
    )

    champion_predictions, challenger_predictions = (
        split_models(
            evaluated
        )
    )

    champion_metrics = (
        calculate_model_metrics(
            predictions=champion_predictions,
            model_name="CHAMPION",
        )
    )

    challenger_metrics = (
        calculate_model_metrics(
            predictions=challenger_predictions,
            model_name="CHALLENGER",
        )
    )

    promotion = (
        evaluate_promotion_eligibility(
            champion_metrics=champion_metrics,
            challenger_metrics=challenger_metrics,
            config=config,
        )
    )

    return {
        "total_predictions": int(
            len(shadow_predictions)
        ),
        "evaluated_predictions": int(
            len(evaluated)
        ),
        "champion": champion_metrics,
        "challenger": challenger_metrics,
        "promotion": promotion,
    }


