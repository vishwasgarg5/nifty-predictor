#!/usr/bin/env python3

"""
Champion / Challenger Performance Evaluation Engine.

This module compares evaluated shadow predictions generated by
the Champion and Challenger models.

Metrics
-------
For each model:

1. Sample Size
2. Average Actual Return
3. Median Actual Return
4. Direction Accuracy
5. Return Prediction MAE
6. Return Prediction RMSE
7. Average Actual Risk
8. Risk Prediction MAE
9. Composite Performance Score

The comparison result is then used to determine whether the
Challenger is eligible for promotion.

Promotion Eligibility
---------------------
The Challenger must:

1. Have enough evaluated samples.
2. Have direction accuracy >= minimum threshold.
3. Have performance improvement >= required threshold.
4. Not exceed risk/error limits.
5. Beat the Champion by the configured margin.

This module does NOT automatically promote the Challenger.
It only calculates performance and promotion eligibility.

Pipeline
--------
shadow_predictions.csv
        │
        ▼
Filter EVALUATED predictions
        │
        ▼
Split by model
        │
   ┌────┴────┐
   ▼         ▼
Champion   Challenger
   │         │
   ▼         ▼
Performance Metrics
   │         │
   └────┬────┘
        ▼
Comparison
        │
        ▼
Promotion Eligibility
"""

